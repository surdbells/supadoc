    /** The English short name, or the code itself when unknown. */
    public static function name(?string $iso2): string
    {
        $iso2 = (string) $iso2;

        return self::ALL[$iso2]['name'] ?? $iso2;
    }

    /**
     * Every distinct calling code without its "+", longest first — so a number
     * is matched to "1268" before "1".
     *
     * @return list<string>
     */
    public static function dialCodes(): array
    {
        static $codes = null;
        if ($codes === null) {
            $codes = array_values(array_unique(array_map(
                static fn (array $c): string => ltrim($c['dial'], '+'),
                self::ALL,
            )));
            usort($codes, static fn (string $a, string $b): int => strlen($b) <=> strlen($a) ?: strcmp($a, $b));
        }

        return $codes;
    }
